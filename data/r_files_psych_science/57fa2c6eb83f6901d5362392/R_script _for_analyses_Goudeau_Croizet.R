### FONCTION IC 95 POUR 4 DEGRES DE LIBERTE
icmoyenne <- function(emoy, sd, eeff, nivconf) {
  int <- (1 - nivconf)/2
  binf <- emoy + qt(int, eeff - 4) * sd/sqrt(eeff)
  bsup <- emoy + qt(1 - int, eeff - 4) * sd/sqrt(eeff)
  bornes <- c(binf, bsup)
  return(bornes)
}

