                  stringsAsFactors = FALSE)

comb$social_1 <- 0
comb$social_2 <- 0
comb$social_3 <- 0

# Codes have rated the texts by dropping the lines without social strategy
comb$social_1[code1_2$V1] <- 1
comb$social_2[code2_2$V1] <- 1
comb$social_3[code3_2$V1] <- 1

##############################
# Check agreement regarding decision
##############################
kappam.fleiss(comb[,c("social_1", "social_2", "social_3")])
# Kappa = .91

# generate binary indicator
# if 0 or  1 raters rated social -> 0
# if 2 or 3 raters rated social -> 1
comb$social_vote <- rowSums(comb[,c("social_1", "social_2", "social_3")]) > 1
table(comb$social_vote[comb$active_vote == TRUE])

